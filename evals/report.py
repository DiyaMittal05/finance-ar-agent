"""Turn evals/results/*.json into a markdown comparison table (evals/RESULTS.md).

    python -m evals.report
"""
from __future__ import annotations

import json
from pathlib import Path

from evals.run import RESULTS

OUT = Path(__file__).parent / "RESULTS.md"


def pct(x):
    return "–" if x is None else f"{x * 100:.0f}%"


def num(x, fmt="{:.2f}"):
    return "–" if x is None else fmt.format(x)


def main() -> None:
    reports = [json.loads(p.read_text()) for p in sorted(RESULTS.glob("*.json"))]
    reports.sort(key=lambda r: (r["provider"] == "mock", r["provider"], r["model"], r["prompt_version"]))
    lines = [
        "# Eval results",
        "",
        "Generated by `python -m evals.report` from `evals/results/*.json`. "
        "Rows from the `mock` provider check the pipeline only and are not model results.",
        "",
        "| Model | Prompt | Cases | Task success | Hallucination rate | Refusal acc. | Clarify acc. "
        "| p50 latency | p95 latency | Tokens/task | Cost/task | Judge |",
        "|---|---|---|---|---|---|---|---|---|---|---|---|",
    ]
    for r in reports:
        s = r["summary"]
        lines.append(
            f"| {r['provider']}/{r['model']} | {r['prompt_version']} | {s['cases']} | {pct(s['task_success'])} "
            f"| {pct(s['hallucination_rate'])} | {pct(s['refusal_accuracy'])} | {pct(s['clarify_accuracy'])} "
            f"| {num(s['latency_p50_s'])}s | {num(s['latency_p95_s'])}s | {num(s['tokens_per_task'], '{:.0f}')} "
            f"| {num(s['cost_per_task_usd'], '${:.4f}')} | {r['judge'] or '–'} |")
    lines += ["", "## Success by category", "",
              "| Model | Prompt | " + " | ".join(sorted({c for r in reports for c in r['summary']['by_category']}))
              + " |"]
    cats = sorted({c for r in reports for c in r["summary"]["by_category"]})
    lines.append("|---|---|" + "---|" * len(cats))
    for r in reports:
        bc = r["summary"]["by_category"]
        lines.append(f"| {r['provider']}/{r['model']} | {r['prompt_version']} | "
                     + " | ".join(pct(bc.get(c)) for c in cats) + " |")
    OUT.write_text("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
